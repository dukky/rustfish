def read_const(src, name):
    m = re.search(rf"^pub\(crate\) const {name}: usize = (\d+);", src, re.MULTILINE)
    return int(m.group(1)) if m else None


def set_const(src, name, value):
    return re.sub(rf"^(pub\(crate\) const {name}: usize = )\d+;", rf"\g<1>{value};",
                  src, count=1, flags=re.MULTILINE)


RESCALE_RE = re.compile(r"factor (\S+): clipped (\d+) of")
ACHIEVED_RE = re.compile(r"re-rounded -> x(\S+)")


def rescale_to(trainer_bin, net, out, *, buckets, layout, ref, ref_buckets, ref_layout, val,
               norm="slope", threads=2, nice=False):
    """`nnue-trainer rescale --match`: write `out` = `net` with its output layer
    scaled to `ref`'s eval scale on `val`. Returns {factor, achieved, clipped, text}."""
    cmd = (["nice"] if nice else []) + [
        trainer_bin, "rescale", "--net", net, "--out", out, "--buckets", buckets, "--king-buckets", layout,
        "--match", ref, "--ref-buckets", ref_buckets, "--ref-king-buckets", ref_layout, "--val", val,
        "--norm", norm, "--threads", threads]
    cmd = [str(c) for c in cmd]
    print("+", " ".join(cmd), flush=True)
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"rescale failed ({r.returncode}): {(r.stderr or r.stdout)[-2000:]}")
    m, a = RESCALE_RE.search(r.stdout), ACHIEVED_RE.search(r.stdout)
    if not m:
        raise RuntimeError(f"cannot parse rescale output {r.stdout!r}")
    return {"factor": float(m.group(1)), "clipped": int(m.group(2)),
            "achieved": float(a.group(1)) if a else None, "text": r.stdout.strip()}


def cmd_embed(args):
    d = Path(args.data_dir).expanduser()
    net = Path(args.net).expanduser()
    if not net.exists():
        die(f"missing net {net}")
    layout_const, kb = KING_LAYOUTS[args.king_buckets]
    want = net_bytes(args.hidden, args.buckets, kb, args.head)
    if net.stat().st_size != want:
        die(f"{net} is {net.stat().st_size} bytes; H={args.hidden} buckets={args.buckets} "
            f"king-buckets={args.king_buckets}{' head' if args.head else ''} needs {want}. Wrong shape?")
    if args.head and args.match_scale:
        die("--match-scale rescales the linear output only; not for --head nets")
    branch = f"nnue-{args.name}"
    if subprocess.run(["git", "-C", REPO, "rev-parse", "--verify", "--quiet", branch],
                      capture_output=True).returncode == 0:
        die(f"branch {branch} already exists locally")
    run(["git", "-C", REPO, "fetch", "--quiet", "origin"])
    wt = Path(tempfile.mkdtemp(prefix=f"netloop-{args.name}-"))
    wt.rmdir()
    run(["git", "-C", REPO, "worktree", "add", "-b", branch, wt, args.base])
    ok = False
    try:
        nnue_rs = wt / "src/nnue.rs"
        src = nnue_rs.read_text()
        base_h, base_b = read_const(src, "H"), read_const(src, "BUCKETS")
        if base_h is None:
            die(f"no `pub(crate) const H` in {args.base}:src/nnue.rs")
        if base_b is None and args.buckets > 1:
            die(f"{args.base} has no BUCKETS constant (output buckets live on origin/nnue-arch); "
                f"use --base with bucket support for a {args.buckets}-bucket net")
        m = re.search(KING_LAYOUT_RE, src, re.MULTILINE)
        base_layout = m.group(2) if m else "LAYOUT_NONE"
        if m is None and args.king_buckets != "none":
            die(f"{args.base} has no KING_LAYOUT constant (king buckets live on origin/king-buckets)")
        if base_layout != layout_const:
            src = re.sub(KING_LAYOUT_RE, rf"\g<1>{layout_const};", src, count=1, flags=re.MULTILINE)
        shape_change = base_h != args.hidden or (base_b or 1) != args.buckets or base_layout != layout_const
        head_re = r"^(pub\(crate\) const HEAD: bool = )(true|false);"
        hm = re.search(head_re, src, re.MULTILINE)
        base_head = hm is not None and hm.group(2) == "true"
        if args.head and hm is None:
            die(f"{args.base} has no HEAD constant (head inference lives on origin/head-v2)")
        if hm is not None and base_head != args.head:
            src = re.sub(head_re, rf"\g<1>{'true' if args.head else 'false'};", src, count=1, flags=re.MULTILINE)
            shape_change = True
        if base_h != args.hidden:
            src = set_const(src, "H", args.hidden)
        if base_b is not None and base_b != args.buckets:
            src = set_const(src, "BUCKETS", args.buckets)
        nnue_rs.write_text(src)
        scale_note, scale_achieved = "", None
        if args.match_scale:
            if args.match_scale == "base":
                ref = wt / "net/base-ref.bin"
                shutil.copyfile(wt / "net/nnue.bin", ref)
                ref_b = base_b or 1
                ref_layout = base_layout[len("LAYOUT_"):].lower()
            else:
                ref = Path(args.match_scale).expanduser()
                ref_b = args.match_ref_buckets or args.buckets
                ref_layout = args.match_ref_king_buckets or args.king_buckets
            val = Path(args.match_val).expanduser() if args.match_val else d / "val.bin"
            scaled = wt / "net/scaled.bin"
            res = rescale_to(trainer(args), net, scaled, buckets=args.buckets, layout=args.king_buckets,
                             ref=ref, ref_buckets=ref_b, ref_layout=ref_layout, val=val, norm=args.match_norm)
            print(res["text"])
            if res["clipped"]:
                print(f"warning: {res['clipped']} output weights clipped to +-127")
            achieved = res["achieved"] if res["achieved"] is not None else res["factor"]
            scale_achieved = achieved
            scale_note = (f"Output layer scaled x{achieved:.4f} ({args.match_norm} match to "
                          f"{args.match_scale} on {val.name}; {res['clipped']} weights clipped).\n")
            shutil.copyfile(scaled, wt / "net/nnue.bin")
            scaled.unlink()
            if args.match_scale == "base":
                ref.unlink()
        else:
            shutil.copyfile(net, wt / "net/nnue.bin")

        run(["cargo", "build", "--release", "--quiet"], cwd=wt)
        # The queue runs `cargo test --release` too (start()); failing here is
        # cheaper than a branch that ends needs-human there.
        if subprocess.run(["cargo", "test", "--release", "--quiet"], cwd=wt).returncode != 0:
            die("cargo test --release failed on the embedded branch")
        engine = wt / "target/release/rustfish"
        t = subprocess.run([str(engine)], input="perfttest\nselftest 100\nquit\n",
                           capture_output=True, text=True, check=True).stdout
        if "FAIL" in t or "perfttest summary" not in t:
            die("perfttest/selftest failed:\n" + t[-3000:])
        print([l for l in t.splitlines() if "perfttest summary" in l][0])
        nodes, nps = load_check_bench().run_bench(str(engine))
        print(f"bench: {nodes} nodes ({nps} nps)")

        log = d / f"{args.name}.log"
        exp = summary_text(args.name, parse_log(log.read_text())) if log.exists() else \
            f"(no training log at {log})"
        shape = (f"H {base_h}->{args.hidden}, buckets {base_b or 1}->{args.buckets}, "
                 f"king layout {base_layout}->{layout_const}") if shape_change \
            else f"same shape (H={args.hidden}, buckets={args.buckets}, {layout_const})"
        msg = (f"NNUE: {args.name} net\n\n"
               f"Net {args.name} on {args.base}; {shape}.\n"
               + (f"{args.notes}\n" if args.notes else "")
               + scale_note
               + f"\n{exp}\n\nBench: {nodes}\n\n"
               "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\n")
        run(["git", "add", "net/nnue.bin", "src/nnue.rs"], cwd=wt)
        run(["git", "commit", "--quiet", "-F", "-"], cwd=wt, input=msg, text=True)
        if args.no_push:
            print(f"--no-push: branch {branch} committed, not pushed")
        else:
            run(["git", "push", "-u", "origin", branch], cwd=wt)
        ok = True
    finally:
        if ok or not args.keep_worktree:
            subprocess.run(["git", "-C", str(REPO), "worktree", "remove", "--force", str(wt)])
            if not ok:
                subprocess.run(["git", "-C", str(REPO), "branch", "-D", branch])
        else:
            print(f"worktree kept at {wt}")

    if args.no_record:
        print("--no-record: net/experiments.jsonl not updated")
    elif args.no_push:
        print(f"--no-push: not recording on main (later: record-local --name {args.name} --branch {branch} ...)")
    else:
        row = row_from_args(args, args.name, branch, net=net)
        if row["hidden"] is None:  # no training log: the shape is known from the flags
            row.update(hidden=args.hidden, buckets=args.buckets)
        if args.king_buckets != "none":
            row["king_buckets"] = args.king_buckets
        if scale_achieved is not None:
            row["output_scale"] = round(scale_achieved, 4)
        record_and_push(row, "embed")

    mode = "stc" if shape_change else "net-gate"
    qcmd = f"python3 scripts/queue.py add {branch}:{mode} --front"
    if args.queue:
        if args.no_push:
            die("--queue needs the branch pushed")
        run(["python3", REPO / "scripts/queue.py", "add", f"{branch}:{mode}", "--front"], cwd=REPO)
    else:
        print(f"\nto queue:\n  {qcmd}")


