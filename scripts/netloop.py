#!/usr/bin/env python3
"""One NNUE generation step on the laptop, with no manual glue.

Subcommands (see docs/nnue-experiments.md, "Running a generation"):

  fetch   download a merged datagen artifact and convert it to s<seed>.bin
  pool    globally shuffle several s<seed>.bin files into one pool
  train   run `nnue-trainer train` with the fixed val set, log, summarise
  embed   put a net on a fresh `nnue-<name>` branch, test, bench, commit, push
  record  append / update a row in net/experiments.jsonl

Python stdlib only. Heavy work is done by tools/nnue-trainer (std-only Rust)
and cargo; this script only sequences it.
"""
import argparse
import datetime
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
GH_REPO = "dukky/rustfish"
DEFAULT_DATA = Path("~/rustfish-data").expanduser()
DEFAULT_TRAINER = REPO / "tools/nnue-trainer/target/release/nnue-trainer"
EXPERIMENTS = REPO / "net/experiments.jsonl"
QUARANTINED = {7}  # generated by the rejected net5; see docs/nnue-experiments.md
INPUTS = 768

EPOCH_RE = re.compile(
    r"^epoch (\d+) lr (\S+) train (\S+) val (\S+) \(quantized (\S+)\)", re.MULTILINE)
HEADER_RE = re.compile(r"^train H=(\d+) buckets=(\d+) .*?epochs=(\d+) x (\d+)", re.MULTILINE)
START_RE = re.compile(r"^start val loss (\S+)", re.MULTILINE)


def die(msg):
    sys.exit(f"netloop: {msg}")


def run(cmd, **kw):
    print("+", " ".join(str(c) for c in cmd), flush=True)
    return subprocess.run([str(c) for c in cmd], check=True, **kw)


def trainer(args):
    t = Path(args.trainer).expanduser()
    if not t.exists():
        die(f"trainer not found at {t}; build it with "
            f"`cargo build --release --manifest-path {REPO}/tools/nnue-trainer/Cargo.toml`")
    return t


def data_dir(args):
    d = Path(args.data_dir).expanduser()
    d.mkdir(parents=True, exist_ok=True)
    return d


def parse_seeds(s):
    try:
        return [int(x) for x in s.split(",") if x.strip()]
    except ValueError:
        die(f"bad seed list {s!r} (want e.g. 4,5,6)")


def net_bytes(h, buckets):
    return (INPUTS * h + h + buckets * (2 * h + 1)) * 2


# ------------------------------------------------------------------ log parsing

def parse_log(text):
    """Parse trainer stdout. Returns a dict with header info and per-epoch rows."""
    out = {"hidden": None, "buckets": None, "epochs": None, "positions_per_epoch": None,
           "start_val": None, "rows": []}
    m = HEADER_RE.search(text)
    if m:
        out["hidden"], out["buckets"], out["epochs"], out["positions_per_epoch"] = map(int, m.groups())
    m = START_RE.search(text)
    if m:
        out["start_val"] = float(m.group(1))
    for m in EPOCH_RE.finditer(text):
        out["rows"].append({"epoch": int(m.group(1)), "lr": float(m.group(2)),
                            "train": float(m.group(3)), "val": float(m.group(4)),
                            "quant": float(m.group(5))})
    return out


def summary_text(name, p):
    lines = [f"{name}: H={p['hidden']} buckets={p['buckets']} epochs={p['epochs']} "
             f"x {p['positions_per_epoch']} positions"]
    if p["start_val"] is not None:
        lines.append(f"start val {p['start_val']:.6f}")
    if p["rows"]:
        lines.append(f"{'epoch':>5} {'lr':>9} {'train':>9} {'val':>9} {'quant':>9}")
        for r in p["rows"]:
            lines.append(f"{r['epoch']:>5} {r['lr']:>9.2e} {r['train']:>9.6f} "
                         f"{r['val']:>9.6f} {r['quant']:>9.6f}")
        best = min(p["rows"], key=lambda r: r["val"])
        last = p["rows"][-1]
        lines.append(f"final val {last['val']:.6f} (quantized {last['quant']:.6f}); "
                     f"best val {best['val']:.6f} at epoch {best['epoch']}")
    else:
        lines.append("no epoch lines found")
    return "\n".join(lines)


# ------------------------------------------------------------------ fetch

def cmd_fetch(args):
    d = data_dir(args)
    out = d / f"s{args.seed}.bin"
    if out.exists():
        print(f"{out} exists; skipping")
        return
    if args.seed in QUARANTINED and not args.force:
        die(f"seed {args.seed} is quarantined (see docs/nnue-experiments.md); --force to override")
    res = subprocess.run(["gh", "api", f"repos/{GH_REPO}/actions/runs/{args.run}/artifacts",
                          "--paginate", "--jq", ".artifacts[].name"],
                         capture_output=True, text=True, check=True)
    names = [n for n in res.stdout.split()
             if n.startswith(f"datagen-s{args.seed}-n") and "shard" not in n and "engine" not in n]
    if len(names) != 1:
        die(f"expected one merged datagen-s{args.seed}-n* artifact in run {args.run}, "
            f"found {names or 'none'} (all: {res.stdout.split()})")
    name = names[0]
    tmp = Path(tempfile.mkdtemp(prefix=f"fetch-s{args.seed}-", dir=d))
    try:
        run(["gh", "run", "download", str(args.run), "-R", GH_REPO, "-n", name, "-D", tmp])
        gz = sorted(tmp.rglob("*.gz"))
        if len(gz) != 1:
            die(f"expected one .gz in artifact {name}, found {[str(g) for g in gz]}")
        part = out.with_suffix(".bin.part")
        print(f"+ gunzip -c {gz[0]} | nnue-trainer convert - {part}", flush=True)
        gun = subprocess.Popen(["gunzip", "-c", str(gz[0])], stdout=subprocess.PIPE)
        conv = subprocess.run([str(trainer(args)), "convert", "-", str(part)], stdin=gun.stdout)
        gun.stdout.close()
        if gun.wait() != 0 or conv.returncode != 0:
            part.unlink(missing_ok=True)
            die("convert failed")
        part.rename(out)
        print(f"wrote {out} ({out.stat().st_size // 32} positions)")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


# ------------------------------------------------------------------ pool

def cmd_pool(args):
    d = data_dir(args)
    seeds = parse_seeds(args.seeds)
    bad = sorted(set(seeds) & QUARANTINED)
    if bad and not args.force:
        die(f"seed(s) {bad} are quarantined (see docs/nnue-experiments.md); --force to override")
    out = Path(args.out)
    if not out.is_absolute():
        out = d / out
    if out.exists() and not args.force:
        print(f"{out} exists; skipping (--force to rebuild)")
        return
    files = [d / f"s{s}.bin" for s in seeds]
    missing = [str(f) for f in files if not f.exists()]
    if missing:
        die(f"missing: {missing} (run `netloop.py fetch` first)")
    run([trainer(args), "shuffle", "--out", out, "--seed", args.shuffle_seed, *files])
    print(f"wrote {out} ({out.stat().st_size // 32} positions from seeds {seeds})")


# ------------------------------------------------------------------ train

def cmd_train(args, extra):
    d = data_dir(args)
    pool = Path(args.pool)
    if not pool.is_absolute():
        pool = d / pool
    val = Path(args.val) if args.val else d / "val.bin"
    for f in (pool, val):
        if not f.exists():
            die(f"missing {f}")
    out = d / f"{args.name}.bin"
    log = d / f"{args.name}.log"
    if out.exists() and not args.force:
        die(f"{out} exists; pick a new --name or pass --force")
    cmd = [trainer(args), "train", "--data", pool, "--val", val, "--out", out,
           "--hidden", args.hidden, "--buckets", args.buckets, "--epochs", args.epochs]
    if args.init:
        cmd += ["--init", Path(args.init).expanduser()]
    cmd += extra
    cmd = [str(c) for c in cmd]
    print("+", " ".join(cmd), flush=True)
    with open(log, "w") as lf:
        lf.write("# " + " ".join(cmd) + "\n")
        lf.flush()
        p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, bufsize=1)
        for line in p.stdout:
            sys.stdout.write(line)
            lf.write(line)
            lf.flush()
        rc = p.wait()
    print()
    print(summary_text(args.name, parse_log(log.read_text())))
    print(f"log: {log}\nnet: {out}")
    if rc != 0:
        die(f"trainer exited with {rc}")


# ------------------------------------------------------------------ embed

def load_check_bench():
    spec = importlib.util.spec_from_file_location("check_bench", REPO / "scripts/check_bench.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def read_const(src, name):
    m = re.search(rf"^pub\(crate\) const {name}: usize = (\d+);", src, re.MULTILINE)
    return int(m.group(1)) if m else None


def set_const(src, name, value):
    return re.sub(rf"^(pub\(crate\) const {name}: usize = )\d+;", rf"\g<1>{value};",
                  src, count=1, flags=re.MULTILINE)


def cmd_embed(args):
    d = Path(args.data_dir).expanduser()
    net = Path(args.net).expanduser()
    if not net.exists():
        die(f"missing net {net}")
    want = net_bytes(args.hidden, args.buckets)
    if net.stat().st_size != want:
        die(f"{net} is {net.stat().st_size} bytes; H={args.hidden} buckets={args.buckets} "
            f"needs {want}. Wrong shape?")
    branch = f"nnue-{args.name}"
    if subprocess.run(["git", "-C", REPO, "rev-parse", "--verify", "--quiet", branch],
                      capture_output=True).returncode == 0:
        die(f"branch {branch} already exists locally")
    run(["git", "-C", REPO, "fetch", "--quiet", "origin"])
    wt = Path(tempfile.mkdtemp(prefix=f"netloop-{args.name}-"))
    wt.rmdir()
    run(["git", "-C", REPO, "worktree", "add", "-b", branch, wt, args.base])
    ok = False
    try:
        nnue_rs = wt / "src/nnue.rs"
        src = nnue_rs.read_text()
        base_h, base_b = read_const(src, "H"), read_const(src, "BUCKETS")
        if base_h is None:
            die(f"no `pub(crate) const H` in {args.base}:src/nnue.rs")
        if base_b is None and args.buckets > 1:
            die(f"{args.base} has no BUCKETS constant (output buckets live on origin/nnue-arch); "
                f"use --base with bucket support for a {args.buckets}-bucket net")
        shape_change = base_h != args.hidden or (base_b or 1) != args.buckets
        if base_h != args.hidden:
            src = set_const(src, "H", args.hidden)
        if base_b is not None and base_b != args.buckets:
            src = set_const(src, "BUCKETS", args.buckets)
        nnue_rs.write_text(src)
        shutil.copyfile(net, wt / "net/nnue.bin")

        run(["cargo", "build", "--release", "--quiet"], cwd=wt)
        engine = wt / "target/release/rustfish"
        t = subprocess.run([str(engine)], input="perfttest\nselftest 100\nquit\n",
                           capture_output=True, text=True, check=True).stdout
        if "FAIL" in t or "perfttest summary" not in t:
            die("perfttest/selftest failed:\n" + t[-3000:])
        print([l for l in t.splitlines() if "perfttest summary" in l][0])
        nodes, nps = load_check_bench().run_bench(str(engine))
        print(f"bench: {nodes} nodes ({nps} nps)")

        log = d / f"{args.name}.log"
        exp = summary_text(args.name, parse_log(log.read_text())) if log.exists() else \
            f"(no training log at {log})"
        shape = f"H {base_h}->{args.hidden}, buckets {base_b or 1}->{args.buckets}" if shape_change \
            else f"same shape (H={args.hidden}, buckets={args.buckets})"
        msg = (f"NNUE: {args.name} net\n\n"
               f"Net {args.name} on {args.base}; {shape}.\n"
               + (f"{args.notes}\n" if args.notes else "")
               + f"\n{exp}\n\nBench: {nodes}\n\n"
               "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\n")
        run(["git", "add", "net/nnue.bin", "src/nnue.rs"], cwd=wt)
        run(["git", "commit", "--quiet", "-F", "-"], cwd=wt, input=msg, text=True)
        if args.no_push:
            print(f"--no-push: branch {branch} committed, not pushed")
        else:
            run(["git", "push", "-u", "origin", branch], cwd=wt)
        ok = True
    finally:
        if ok or not args.keep_worktree:
            subprocess.run(["git", "-C", str(REPO), "worktree", "remove", "--force", str(wt)])
            if not ok:
                subprocess.run(["git", "-C", str(REPO), "branch", "-D", branch])
        else:
            print(f"worktree kept at {wt}")

    mode = "stc" if shape_change else "net-gate"
    qcmd = f"python3 scripts/queue.py add {branch}:{mode} --front"
    if args.queue:
        if args.no_push:
            die("--queue needs the branch pushed")
        run(["python3", REPO / "scripts/queue.py", "add", f"{branch}:{mode}", "--front"], cwd=REPO)
    else:
        print(f"\nto queue:\n  {qcmd}")


# ------------------------------------------------------------------ record

def load_rows():
    if not EXPERIMENTS.exists():
        return []
    return [json.loads(l) for l in EXPERIMENTS.read_text().splitlines() if l.strip()]


def save_rows(rows):
    EXPERIMENTS.parent.mkdir(parents=True, exist_ok=True)
    EXPERIMENTS.write_text("".join(json.dumps(r) + "\n" for r in rows))


def cmd_record(args):
    rows = load_rows()
    idx = next((i for i, r in enumerate(rows) if r.get("id") == args.name), None)
    updating = any(v is not None for v in (args.sprt_elo, args.sprt_ci, args.sprt_games, args.verdict))
    if updating:
        if idx is None:
            die(f"no row with id {args.name!r} in {EXPERIMENTS}")
        row = rows[idx]
        sprt = dict(row.get("sprt") or {})
        if args.sprt_elo is not None:
            sprt["elo"] = args.sprt_elo
        if args.sprt_ci is not None:
            try:
                lo, hi = (float(x) for x in args.sprt_ci.split(","))
            except ValueError:
                die("--sprt-ci wants lo,hi")
            sprt["ci"] = [lo, hi]
        if args.sprt_games is not None:
            sprt["games"] = args.sprt_games
        if sprt:
            row["sprt"] = sprt
        if args.verdict is not None:
            row["verdict"] = args.verdict
        if args.notes:
            row["notes"] = (row.get("notes") + "; " if row.get("notes") else "") + args.notes
        save_rows(rows)
        print(json.dumps(row))
        return

    if idx is not None:
        die(f"row {args.name!r} already exists; pass --sprt-*/--verdict to update it")
    log = Path(args.log).expanduser() if args.log else \
        Path(args.data_dir).expanduser() / f"{args.name}.log"
    p = parse_log(log.read_text()) if log.exists() else parse_log("")
    if not log.exists():
        print(f"note: no log at {log}; loss fields come from flags only", file=sys.stderr)
    last = p["rows"][-1] if p["rows"] else {}
    pick = lambda flag, parsed: flag if flag is not None else parsed
    row = {
        "id": args.name,
        "date": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
        "hidden": pick(args.hidden, p["hidden"]),
        "buckets": pick(args.buckets, p["buckets"]),
        "seeds": parse_seeds(args.seeds) if args.seeds else None,
        "epochs": pick(args.epochs, p["epochs"]),
        "positions_per_epoch": pick(args.positions_per_epoch, p["positions_per_epoch"]),
        "val_loss": pick(args.val_loss, last.get("val")),
        "val_loss_quantized": pick(args.val_loss_quantized, last.get("quant")),
        "baseline": args.baseline,
        "branch": args.branch if args.branch is not None else f"nnue-{args.name}",
        "notes": args.notes or "",
        "sprt": None,
        "verdict": None,
    }
    rows.append(row)
    save_rows(rows)
    print(json.dumps(row))


# ------------------------------------------------------------------ main

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    def common(p, trainer_needed=True):
        p.allow_abbrev = False  # train passes unknown flags through to nnue-trainer
        p.add_argument("--data-dir", default=str(DEFAULT_DATA), help="default ~/rustfish-data")
        if trainer_needed:
            p.add_argument("--trainer", default=str(DEFAULT_TRAINER), help="nnue-trainer binary")
        return p

    p = common(sub.add_parser("fetch", help="download + convert a merged datagen artifact"))
    p.add_argument("--run", required=True, help="datagen workflow run id")
    p.add_argument("--seed", required=True, type=int)
    p.add_argument("--force", action="store_true", help="allow a quarantined seed")

    p = common(sub.add_parser("pool", help="shuffle s<seed>.bin files into one pool"))
    p.add_argument("--out", required=True, help="pool file (relative to --data-dir)")
    p.add_argument("--seeds", required=True, help="comma list, e.g. 4,5,6,8,9,10,11")
    p.add_argument("--shuffle-seed", type=int, default=1)
    p.add_argument("--force", action="store_true", help="allow quarantined seeds / rebuild an existing pool")

    p = common(sub.add_parser("train", help="train a net; extra args go to nnue-trainer train"))
    p.add_argument("--name", required=True)
    p.add_argument("--pool", required=True, help="pool file (relative to --data-dir)")
    p.add_argument("--val", help="validation file (default <data-dir>/val.bin)")
    p.add_argument("--hidden", type=int, required=True)
    p.add_argument("--buckets", type=int, required=True)
    p.add_argument("--epochs", type=int, required=True)
    p.add_argument("--init", help="start from an existing i16 net")
    p.add_argument("--force", action="store_true", help="overwrite an existing <name>.bin")

    p = common(sub.add_parser("embed", help="commit a net on branch nnue-<name>, bench, push"), False)
    p.add_argument("--name", required=True)
    p.add_argument("--net", required=True)
    p.add_argument("--base", default="origin/main")
    p.add_argument("--hidden", type=int, required=True)
    p.add_argument("--buckets", type=int, required=True)
    p.add_argument("--notes", default="", help="extra line for the commit message")
    p.add_argument("--no-push", action="store_true")
    p.add_argument("--keep-worktree", action="store_true", help="keep the temp worktree on failure")
    p.add_argument("--queue", action="store_true", help="also run the queue.py add command")

    p = common(sub.add_parser("record", help="add or update a row in net/experiments.jsonl"), False)
    p.add_argument("--name", required=True)
    p.add_argument("--log", help="training log (default <data-dir>/<name>.log)")
    p.add_argument("--seeds")
    p.add_argument("--hidden", type=int)
    p.add_argument("--buckets", type=int)
    p.add_argument("--epochs", type=int)
    p.add_argument("--positions-per-epoch", type=int)
    p.add_argument("--val-loss", type=float)
    p.add_argument("--val-loss-quantized", type=float)
    p.add_argument("--baseline", default="net4")
    p.add_argument("--branch")
    p.add_argument("--notes", default="")
    p.add_argument("--sprt-elo", type=float)
    p.add_argument("--sprt-ci", help="lo,hi")
    p.add_argument("--sprt-games", type=int)
    p.add_argument("--verdict", choices=["merged", "rejected"])

    args, extra = ap.parse_known_args()
    if extra and args.cmd != "train":
        ap.error(f"unrecognized arguments: {' '.join(extra)}")
    if args.cmd == "train":
        cmd_train(args, extra)
    else:
        {"fetch": cmd_fetch, "pool": cmd_pool, "embed": cmd_embed, "record": cmd_record}[args.cmd](args)


if __name__ == "__main__":
    main()
