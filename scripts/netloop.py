def load_rows():
    if not EXPERIMENTS.exists():
        return []
    return parse_rows(EXPERIMENTS.read_text())


def parse_rows(text):
    return [json.loads(l) for l in text.splitlines() if l.strip()]


def dump_rows(rows):
    return "".join(json.dumps(r) + "\n" for r in rows)


def save_rows(rows):
    EXPERIMENTS.parent.mkdir(parents=True, exist_ok=True)
    EXPERIMENTS.write_text(dump_rows(rows))


def utc_iso(ts=None):
    t = datetime.datetime.now(datetime.timezone.utc) if ts is None else \
        datetime.datetime.fromtimestamp(ts, datetime.timezone.utc)
    return t.replace(microsecond=0).strftime("%Y-%m-%dT%H:%M:%SZ")


def experiment_row(name, p, *, baseline, branch, notes="", seeds=None, date=None, extra=None):
    """An experiments.jsonl row from a parsed training log (parse_log) plus args.
    Optional fields (king_buckets, mean_abs_eval, train_data, init, best_scale_*)
    are only present when known, so the core shape stays the same."""
    last = p["rows"][-1] if p["rows"] else {}
    row = {
        "id": name,
        "date": date or utc_iso(),
        "hidden": p["hidden"],
        "buckets": p["buckets"],
        "seeds": seeds,
        "epochs": p["epochs"],
        "positions_per_epoch": p["positions_per_epoch"],
        "val_loss": last.get("val"),
        "val_loss_quantized": last.get("quant"),
        "baseline": baseline,
        "branch": branch,
        "notes": notes or "",
        "sprt": None,
    }
    opt = {"king_buckets": p.get("king_buckets"), "mean_abs_eval": last.get("eval"),
           "train_data": p.get("data"), "init": p.get("init"), **(extra or {})}
    row.update({k: v for k, v in opt.items() if v is not None})
    return row


def upsert_row(rows, row):
    """Insert `row`, or merge it into the row with the same id in place (fields
    the new row leaves empty, e.g. sprt / verdict filled in later, are kept).
    Returns the stored row."""
    for i, r in enumerate(rows):
        if r.get("id") == row["id"]:
            merged = dict(r)
            merged.update({k: v for k, v in row.items() if v is not None and v != ""})
            if str(row.get("branch", "")).startswith("local-") and r.get("branch") \
                    and not str(r["branch"]).startswith("local-"):
                merged["branch"] = r["branch"]  # a net that got a real branch stays on it
            rows[i] = merged
            return merged
    rows.append(row)
    return row


def git_out(repo, *a, env=None, input=None, check=True):
    r = subprocess.run(["git", "-C", str(repo), *map(str, a)], capture_output=True, text=True,
                       env=env, input=input)
    if check and r.returncode != 0:
        raise RuntimeError(f"git {' '.join(map(str, a))} failed: {(r.stderr or r.stdout).strip()[-1500:]}")
    return r


EXP_PATH = "net/experiments.jsonl"


def publish_row(row, *, repo=REPO, remote="origin", ref="main", why="netloop"):
    """Upsert `row` into net/experiments.jsonl on <remote>/<ref> as a data-only
    commit and push it. The commit is built on a freshly fetched <remote>/<ref>
    with a private index (the same result as pull --rebase, without touching any
    checkout or working tree). Retries once on a non-fast-forward; never forces.
    Returns the new commit sha, or None if the row was already up to date."""
    for attempt in (1, 2):
        git_out(repo, "fetch", "--quiet", remote, f"+refs/heads/{ref}:refs/remotes/{remote}/{ref}")
        base = git_out(repo, "rev-parse", f"refs/remotes/{remote}/{ref}").stdout.strip()
        r = git_out(repo, "show", f"{base}:{EXP_PATH}", check=False)
        old = r.stdout if r.returncode == 0 else ""
        rows = parse_rows(old)
        existed = any(x.get("id") == row["id"] for x in rows)
        stored = upsert_row(rows, dict(row))
        new = dump_rows(rows)
        if new == old:
            print(f"netloop: {row['id']} already up to date in {remote}/{ref}:{EXP_PATH}")
            return None
        blob = git_out(repo, "hash-object", "-w", "--stdin", input=new).stdout.strip()
        with tempfile.TemporaryDirectory(prefix="netloop-idx-") as td:
            env = {**os.environ, "GIT_INDEX_FILE": str(Path(td) / "index")}
            git_out(repo, "read-tree", base, env=env)
            git_out(repo, "update-index", "--add", "--cacheinfo", f"100644,{blob},{EXP_PATH}", env=env)
            tree = git_out(repo, "write-tree", env=env).stdout.strip()
        verb = "Update" if existed else "Record"
        msg = (f"{verb} {row['id']} in {EXP_PATH}\n\n"
               f"Data-only commit written by `scripts/netloop.py {why}`.\n\n"
               "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\n")
        commit = git_out(repo, "commit-tree", tree, "-p", base, "-F", "-", input=msg).stdout.strip()
        r = git_out(repo, "push", "--quiet", remote, f"{commit}:refs/heads/{ref}", check=False)
        if r.returncode == 0:
            print(f"netloop: pushed {commit[:7]} ({verb.lower()} {row['id']}) to {remote}/{ref}")
            print(json.dumps(stored))
            return commit
        err = (r.stderr or r.stdout).strip()
        if attempt == 1 and re.search(r"non-fast-forward|fetch first|rejected", err):
            print(f"netloop: push of {row['id']} raced another commit; rebuilding on the new {ref}", flush=True)
            continue
        raise RuntimeError(f"push to {remote}/{ref} failed: {err[-1500:]}")


def best_scale(trainer_bin, net, val, *, buckets, king_buckets="none", threads=2):
    """`nnue-trainer eval --best-scale` -> {best_scale_val, best_scale_factor}."""
    cmd = ["nice", trainer_bin, "eval", "--net", net, "--val", val, "--buckets", buckets,
           "--threads", threads, "--best-scale"]
    if king_buckets and king_buckets != "none":
        cmd += ["--king-buckets", king_buckets]
    cmd = [str(c) for c in cmd]
    print("+", " ".join(cmd), flush=True)
    r = subprocess.run(cmd, capture_output=True, text=True)
    m = BEST_SCALE_RE.search(r.stdout)
    if r.returncode != 0 or not m:
        raise RuntimeError(f"eval --best-scale failed ({r.returncode}): {(r.stderr or r.stdout)[-1000:]}")
    return {"best_scale_val": float(m.group(2)), "best_scale_factor": float(m.group(1))}


def row_from_args(args, name, branch, *, net=None):
    """A row from <--log> (default <data-dir>/<name>.log) and the shared
    recording flags (--baseline, --notes, --seeds, --best-scale, shape/loss
    overrides where the subcommand has them)."""
    d = Path(args.data_dir).expanduser()
    log = Path(args.log).expanduser() if getattr(args, "log", None) else d / f"{name}.log"
    if log.exists():
        p, date = parse_log(log.read_text()), utc_iso(log.stat().st_mtime)
    else:
        print(f"note: no log at {log}; shape/loss fields come from flags only", file=sys.stderr)
        p, date = parse_log(""), None
    for key in ("hidden", "buckets", "epochs", "positions_per_epoch"):
        if getattr(args, key, None) is not None and p[key] is None:
            p[key] = getattr(args, key)
    extra = {}
    if getattr(args, "best_scale", False):
        net = Path(net or d / f"{name}.bin").expanduser()
        val = Path(args.best_scale_val).expanduser() if args.best_scale_val else d / "val.bin"
        try:
            extra = best_scale(trainer(args), net, val, buckets=p["buckets"] or 1,
                               king_buckets=p["king_buckets"] or getattr(args, "king_buckets", "none"))
        except (RuntimeError, OSError) as e:
            print(f"warning: --best-scale skipped: {e}", file=sys.stderr)
    row = experiment_row(name, p, baseline=args.baseline, branch=branch, notes=args.notes,
                         seeds=parse_seeds(args.seeds) if getattr(args, "seeds", None) else None,
                         date=date, extra=extra)
    for key in ("val_loss", "val_loss_quantized"):
        if getattr(args, key, None) is not None:
            row[key] = getattr(args, key)
    return row


def record_and_push(row, why):
    """Push the row to main; on failure warn and go on (the net itself is done)."""
    try:
        publish_row(row, why=why)
    except (RuntimeError, OSError) as e:
        print(f"warning: could not record {row['id']} on main: {e}\n"
              f"retry: python3 scripts/netloop.py record-local --name {row['id']} --branch {row['branch']} "
              f"--baseline {row['baseline']!r} ...\nrow: {json.dumps(row)}", file=sys.stderr)


