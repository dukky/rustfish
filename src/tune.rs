use super::*;

const KIND_NAMES: [&str; 6] = ["pawn", "knight", "bishop", "rook", "queen", "king"];

/// Render middlegame/endgame piece-square tables (material included, a1..h8
/// from White's side) as the contents of src/psqt.rs.
pub(crate) fn format_psqt(mg: &[[i32; 64]; 6], eg: &[[i32; 64]; 6], note: &str) -> String {
    let mut out = String::new();
    out.push_str("// Generated by the `tune` command (src/tune.rs); edit by re-tuning, not by hand.\n");
    out.push_str(&format!("// {}\n", note));
    out.push_str("// Piece-square values with material folded in, indexed [piece][square]\n");
    out.push_str("// with squares a1..h8 from White's side (Black uses square ^ 56).\n\n");
    for (name, table) in [("PSQT_MG", mg), ("PSQT_EG", eg)] {
        out.push_str(&format!("pub(crate) const {}: [[i32; 64]; 6] = [\n", name));
        for (k, rows) in table.iter().enumerate() {
            out.push_str(&format!("    // {}\n    [\n", KIND_NAMES[k]));
            for rank in 0..8 {
                let row: Vec<String> = (0..8).map(|f| format!("{:5}", rows[rank * 8 + f])).collect();
                out.push_str(&format!("        {},\n", row.join(",")));
            }
            out.push_str("    ],\n");
        }
        out.push_str("];\n\n");
    }
    out.trim_end().to_string() + "\n"
}
